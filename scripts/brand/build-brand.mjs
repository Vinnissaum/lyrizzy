// Writes the brand artwork from its single source, src/brand/shield.ts:
//
//   app-icon.svg               app icon source (night tile + backlit window)
//   src-tauri/icons/icon.svg   the same icon, kept beside the rasterized set
//   docs/public/logo.svg       the window alone: docs nav logo and favicon
//   docs/public/brasao.svg     the inscribed window (Cinzel embedded): docs hero
//
// then rasterizes every platform icon with `tauri icon` and copies the three the
// web pages use into public/icons.
//
//   npm run brand:build                 everything
//   npm run brand:build -- --svg-only   skip `tauri icon`
//
// src/brand/shield.test.ts fails when a committed file drifts from brandFiles().
// Node runs src/brand/shield.ts directly (type stripping), so this needs Node 22.18+.
import { execSync } from "node:child_process";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { shieldSvg } from "../../src/brand/shield.ts";
import { isMainModule } from "../is-main-module.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const at = (...parts) => join(root, ...parts);

const header = (what) =>
  `<!-- Lyrizzy: ${what}. Generated by scripts/brand/build-brand.mjs from src/brand/shield.ts; edit those, not this file. -->\n`;

/** Every generated SVG, keyed by its path from the repository root. */
export function brandFiles() {
  const cinzel = readFileSync(at("src/assets/fonts/Cinzel-Bold.woff2")).toString("base64");
  const embeddedCinzel =
    `@font-face{font-family:Cinzel;font-weight:700;` +
    `src:url(data:font/woff2;base64,${cinzel}) format("woff2")}`;
  const icon = header("app icon") + shieldSvg({ tile: true, glow: true, title: "Lyrizzy" }) + "\n";

  return {
    "app-icon.svg": icon,
    "src-tauri/icons/icon.svg": icon,
    "docs/public/logo.svg": header("logo") + shieldSvg({ margin: 8, title: "Lyrizzy" }) + "\n",
    "docs/public/brasao.svg":
      header("the Shield of the Trinity window, with its inscriptions") +
      shieldSvg({
        labels: true,
        glow: true,
        margin: 60,
        css: embeddedCinzel,
        title: "Escudo da Trindade em vitral: Pai, Filho e Espírito Santo",
      }) +
      "\n",
  };
}

if (isMainModule(import.meta.url)) {
  for (const [path, svg] of Object.entries(brandFiles())) {
    writeFileSync(at(path), svg);
    console.log(`wrote ${path}`);
  }

  if (!process.argv.includes("--svg-only")) {
    // Through the shell: on Windows npx is npx.cmd, which execFile cannot start.
    execSync("npx tauri icon app-icon.svg", { cwd: root, stdio: "inherit" });
    for (const name of ["32x32.png", "128x128.png", "icon.ico"]) {
      copyFileSync(at("src-tauri/icons", name), at("public/icons", name));
      console.log(`copied public/icons/${name}`);
    }
  }
}
